#!/usr/bin/env python3
"""Invariant 7: Golden Curve Protection.

Compares current benchmark results against bench/baselines/quality-golden.csv.
Fails if drift >1.5% accuracy or >2.0% VRAM error.
"""

import argparse
import sys
from pathlib import Path

import pandas as pd

GOLDEN_PATH = Path("bench/baselines/quality-golden.csv")
CURRENT_PATH = Path("bench/data/quality-current.csv")  # Generated by bench run

ACCURACY_THRESHOLD = 0.015  # 1.5%
VRAM_THRESHOLD = 0.020  # 2.0%


def main() -> int:
    parser = argparse.ArgumentParser(description="Golden curve drift check (Invariant 7)")
    parser.add_argument(
        "--current",
        type=Path,
        default=CURRENT_PATH,
        help="metric,value CSV to compare against the golden baseline",
    )
    args = parser.parse_args()

    if not GOLDEN_PATH.exists():
        print(f"[FAIL] Golden baseline not found: {GOLDEN_PATH}")
        return 1

    if not args.current.exists():
        print(f"[FAIL] Current results not found: {args.current}")
        print("   Run bench suite first: python bench/run_suite.py")
        return 1

    golden = pd.read_csv(GOLDEN_PATH)
    current = pd.read_csv(args.current)

    # Expected columns: metric, value
    # Metrics: accuracy, vram_mib, latency_ms, throughput_tps
    required_metrics = ["accuracy", "vram_mib"]
    for metric in required_metrics:
        if metric not in golden["metric"].values:
            print(f"[FAIL] Golden missing metric: {metric}")
            return 1
        if metric not in current["metric"].values:
            print(f"[FAIL] Current missing metric: {metric}")
            return 1

    all_ok = True

    # Accuracy check (higher is better)
    golden_acc = golden[golden["metric"] == "accuracy"]["value"].values[0]
    current_acc = current[current["metric"] == "accuracy"]["value"].values[0]
    acc_drift = (golden_acc - current_acc) / golden_acc
    print(f"Accuracy: golden={golden_acc:.4f}, current={current_acc:.4f}, drift={acc_drift:.2%}")
    if acc_drift > ACCURACY_THRESHOLD:
        print(f"  [FAIL] Accuracy drift {acc_drift:.2%} exceeds threshold {ACCURACY_THRESHOLD:.1%}")
        all_ok = False
    else:
        print("  [OK] Accuracy drift within threshold")

    # VRAM check (lower is better)
    golden_vram = golden[golden["metric"] == "vram_mib"]["value"].values[0]
    current_vram = current[current["metric"] == "vram_mib"]["value"].values[0]
    vram_drift = (current_vram - golden_vram) / golden_vram
    print(
        f"VRAM: golden={golden_vram:.1f} MiB, current={current_vram:.1f} MiB, drift={vram_drift:.2%}"
    )
    if vram_drift > VRAM_THRESHOLD:
        print(f"  [FAIL] VRAM drift {vram_drift:.2%} exceeds threshold {VRAM_THRESHOLD:.1%}")
        all_ok = False
    else:
        print("  [OK] VRAM drift within threshold")

    # Optional metrics
    for metric in ["latency_ms", "throughput_tps"]:
        if metric in golden["metric"].values and metric in current["metric"].values:
            g = golden[golden["metric"] == metric]["value"].values[0]
            c = current[current["metric"] == metric]["value"].values[0]
            print(f"{metric}: golden={g:.2f}, current={c:.2f}")

    if all_ok:
        print("\n[OK] Golden curve comparison passed")
        return 0
    else:
        print("\n[FAIL] Golden curve protection triggered - drift exceeds thresholds")
        return 1


if __name__ == "__main__":
    sys.exit(main())
